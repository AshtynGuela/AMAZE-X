import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.BASE_URL??'http://127.0.0.1:5175',dir='.impeccable/review/entry-flight';await fs.mkdir(dir,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'}),errors=[],assets=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.url().includes('/assets/entry/'))assets.push(r.url())});
try{
  await page.goto(base);await expect(page.getByRole('dialog',{name:'AMAZE-X',exact:true})).toBeVisible();
  await page.waitForFunction(()=>document.activeElement?.matches('.mission-welcome'));
  await page.mouse.move(300,300);
  assert.equal(assets.length,0,'Rocket assets must not delay initial landing page');
  const step=async pixels=>{await page.mouse.wheel(0,-pixels);};
  const progress=()=>page.locator('main').getAttribute('data-entry-progress').then(Number);
  await step(220);await expect(page.locator('.welcome-flight')).toHaveAttribute('data-state','ready',{timeout:90000});
  await expect.poll(progress,{timeout:90000}).toBeGreaterThan(.2);
  console.log('ASCENT',await page.locator('.welcome-flight').evaluate(e=>({state:e.dataset.state,progress:e.dataset.progress,opacity:getComputedStyle(e).opacity,canvas:e.querySelector('canvas')?.getBoundingClientRect().toJSON()})));
  await page.screenshot({path:dir+'/01-ascent.png',animations:'disabled',timeout:45000});
  await step(230);await expect.poll(progress,{timeout:30000}).toBeGreaterThan(.44);
  await page.screenshot({path:dir+'/02-boosters.png',animations:'disabled',timeout:45000});
  const paused=await progress();await page.waitForTimeout(700);assert.ok(Math.abs(await progress()-paused)<.002,'Progress must stop with the scroll');
  await step(280);await expect.poll(progress,{timeout:30000}).toBeGreaterThan(.7);
  await page.screenshot({path:dir+'/03-spacecraft.png',animations:'disabled',timeout:45000});
  await step(-280);await expect.poll(progress,{timeout:30000}).toBeLessThan(.46);
  assert.equal(await page.locator('.welcome-flight').getAttribute('data-phase'),'booster-separation');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:dir+'/04-mobile.png',animations:'disabled',timeout:45000});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await step(2000);await expect(page.getByRole('dialog',{name:'AMAZE-X',exact:true})).toHaveCount(0,{timeout:30000});
  await expect(page.locator('.welcome-flight')).toHaveCount(0);
  assert.ok(await page.locator('.view-toolbar').evaluate(el=>!el.closest('[inert]')));
  assert.equal(new Set(assets).size,2);assert.deepEqual(errors,[]);
  await page.close();
  const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'}),reducedAssets=[];
  reduced.on('request',r=>{if(r.url().includes('/assets/entry/'))reducedAssets.push(r.url())});
  await reduced.goto(base);await reduced.getByRole('dialog',{name:'AMAZE-X',exact:true}).press('Enter');
  await expect(reduced.getByRole('dialog',{name:'AMAZE-X',exact:true})).toHaveCount(0,{timeout:90000});assert.equal(reducedAssets.length,0);
  await reduced.close();
  const report={testedUtc:new Date().toISOString(),base,assetRequests:new Set(assets).size,initialRocketRequests:0,scrollPause:true,reverseStaging:true,mobileOverflow:false,entryControlsRestored:true,reducedMotionSkips3D:true,errors};
  await fs.writeFile('data/validation/entry-flight-browser.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close()}
